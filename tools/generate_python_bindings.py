def find_matching_brace(src, open_idx):
    depth = 0
    for i in range(open_idx, len(src)):
        if src[i] == "{":
            depth += 1
        elif src[i] == "}":
            depth -= 1
            if depth == 0:
                return i
    return -1


def sanitize(text):
    """Reduce ``static inline <decl> { ... }`` definitions to ``<decl>;``.

    These helpers live in headers but are not exported by the shared
    library, so ctypesgen must not see their bodies (its C grammar only
    accepts declarations).
    """
    out, pos = [], 0
    for m in re.finditer(r"\bstatic\s+inline\b", text):
        dm = re.match(r"[^{}]*?\{", text[m.end():], re.DOTALL)
        if not dm:
            continue
        decl = dm.group(0)[:-1].strip()
        end = find_matching_brace(text, m.end() + dm.end() - 1)
        if end == -1:
            continue
        out.append(text[pos:m.start()])
        out.append(decl + ";\n")
        pos = end + 1
    out.append(text[pos:])
    return "".join(out)


def collect_headers(include_dir, for_staging=False):
    """Public headers for ctypesgen input; with for_staging, every header
    (stubs included) so nested #includes resolve inside the staged tree."""
    headers = []
    for path in sorted(glob.glob(os.path.join(include_dir, "aroma*.h"))):
        if os.path.basename(path) in SKIP_HEADERS and not for_staging:
            continue
        headers.append(path)
    widgets = os.path.join(include_dir, "widgets")
    if os.path.isdir(widgets):
        headers += sorted(glob.glob(os.path.join(widgets, "*.h")))
    return headers


def stage_headers(headers, include_dir, dest_dir):
    staged = []
    for src in headers:
        rel = os.path.relpath(src, include_dir)
        dst = os.path.join(dest_dir, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(src, encoding="utf-8", errors="replace") as f:
            text = f.read()
        if os.path.basename(src) in STUB_HEADERS:
            guard = os.path.basename(src).replace(".", "_").upper()
            text = ("/* Stub for binding generation: binary font data. */\n"
                    "#ifndef %s\n#define %s\n#endif\n" % (guard, guard))
        else:
            text = sanitize(text)
        with open(dst, "w", encoding="utf-8") as f:
            f.write(text)
        staged.append(dst)
    return staged


def ensure_ctypesgen():
    if VENDOR not in sys.path:
        sys.path.insert(0, VENDOR)
    if not os.path.isfile(os.path.join(VENDOR, "ctypesgen", "main.py")):
        print("error: ctypesgen submodule is empty; run:\n"
              "  git submodule update --init vendors/ctypesgen",
              file=sys.stderr)
        return None
    try:
        from ctypesgen.main import main  # noqa: F401
    except ImportError as exc:
        print("error: cannot import ctypesgen: %s" % exc, file=sys.stderr)
        return None
    if not shutil.which("gcc"):
        print("error: gcc is required (C preprocessor)", file=sys.stderr)
        return None
    return sys.modules["ctypesgen.main"]


def find_lib_dir():
    cands = []
    env = os.environ.get("AROMA_LIB")
    if env and os.path.isfile(env):
        return os.path.dirname(os.path.abspath(env))
    for p in (os.path.join(ROOT, "build", "src", "libaroma.so"),
              os.path.join(ROOT, "build", "python-bindings", "src", "libaroma.so")):
        if os.path.isfile(p):
            return os.path.dirname(p)
    return None


def run_ctypesgen(staged, staged_dir, output, extra_args=()):
    mod = ensure_ctypesgen()
    if mod is None:
        return False
    args = ["-I", staged_dir, "-l", "aroma", "--cpp", CPP,
            "-o", output] + list(extra_args) + staged
    old_argv = sys.argv
    sys.argv = ["ctypesgen"] + args
    try:
        mod.main(args)
    finally:
        sys.argv = old_argv
    return True


def write_wrapper(output):
    rel = os.path.relpath(output, ROOT)
    depth = len(os.path.relpath(ROOT, os.path.dirname(output)).split(os.sep))
    root_up = ", ".join([".."] * max(depth, 1))
    with open(output, "w", encoding="utf-8") as f:
        f.write(WRAPPER_TEMPLATE.format(
            n_headers=len(collect_headers(DEFAULT_INCLUDE)),
            output_rel=rel, root_up='"%s"' % root_up))


def cmd_stats(include_dir):
    headers = collect_headers(include_dir)
    if not headers:
        print("error: no headers found in %s" % include_dir, file=sys.stderr)
        return 1
    if ensure_ctypesgen() is None:
        return 1
    tmp = tempfile.mkdtemp(prefix="aroma-bindgen-")
    try:
        staged_dir = os.path.join(tmp, "staged")
        stage_headers(collect_headers(include_dir, for_staging=True),
                      include_dir, staged_dir)
        staged = [os.path.join(staged_dir, os.path.relpath(h, include_dir))
                  for h in headers]
        js = os.path.join(tmp, "stats.json")
        if not run_ctypesgen(staged, staged_dir, js,
                             ["--output-language", "json"]):
            return 1
        with open(js, encoding="utf-8") as f:
            items = json.load(f)
        kinds = {}
        for item in items:
            kinds[item.get("type", "?")] = kinds.get(item.get("type", "?"), 0) + 1
        print("headers: %d" % len(headers))
        for kind in sorted(kinds):
            print("  %s: %d" % (kind, kinds[kind]))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--include-dir", default=DEFAULT_INCLUDE)
    ap.add_argument("--output", "-o", default=DEFAULT_OUTPUT)
    ap.add_argument("--check", action="store_true",
                    help="import the generated module and report counts")
    ap.add_argument("--stats", action="store_true", help="print parse stats only")
    args = ap.parse_args(argv)

    if args.stats:
        return cmd_stats(args.include_dir)

    headers = collect_headers(args.include_dir)
    if not headers:
        print("error: no headers found in %s" % args.include_dir, file=sys.stderr)
        return 1

    out_dir = os.path.dirname(os.path.abspath(args.output))
    os.makedirs(out_dir, exist_ok=True)
    raw_out = os.path.join(out_dir, RAW_NAME)
    tmp = tempfile.mkdtemp(prefix="aroma-bindgen-")
    try:
        staged_dir = os.path.join(tmp, "staged")
        stage_headers(collect_headers(args.include_dir, for_staging=True),
                      args.include_dir, staged_dir)
        staged = [os.path.join(staged_dir, os.path.relpath(h, args.include_dir))
                  for h in headers]
        extra = []
        lib_dir = find_lib_dir()
        if lib_dir:
            extra = ["-L", lib_dir]
        if not run_ctypesgen(staged, staged_dir, raw_out, extra):
            return 1
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    write_wrapper(args.output)

    n_fn = 0
    with open(raw_out, encoding="utf-8") as f:
        for line in f:
            if ".argtypes = " in line:
                n_fn += 1
    print("wrote %s (+ %s) via ctypesgen (%d headers, ~%d functions)"
          % (args.output, RAW_NAME, len(headers), n_fn))

    if args.check:
        if lib_dir:
            os.environ["LD_LIBRARY_PATH"] = (
                lib_dir + os.pathsep + os.environ.get("LD_LIBRARY_PATH", ""))
        import importlib.util
        spec = importlib.util.spec_from_file_location("aroma_check", args.output)
        mod = importlib.util.module_from_spec(spec)
        try:
            spec.loader.exec_module(mod)
        except Exception as exc:
            print("check: import failed: %s" % exc, file=sys.stderr)
            return 1
        print("check: import ok; lib available: %s" % mod.is_available())
        print("check: bound=%d missing=%d" % (len(mod._BOUND), len(mod._MISSING)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
